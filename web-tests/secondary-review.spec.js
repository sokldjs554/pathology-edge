import { test, expect } from '@playwright/test';
import fs from 'node:fs';
const ihc = JSON.parse(fs.readFileSync(new URL('../dist/ihc/results.json', import.meta.url)));
fs.mkdirSync('captures', { recursive: true });
const shot = (page, name) => page.screenshot({path:`captures/secondary-${name}.png`, fullPage:true});
const ready = page => expect(page.locator('body')).toHaveAttribute('data-phase','ready');
const camera = page => page.locator('#viewerB').evaluate(el => ({center:el.dataset.center.split(',').map(Number),zoom:Number(el.dataset.zoom)}));
const sameCamera = async (page, before) => {
  await expect.poll(async () => { const after=await camera(page); return Math.hypot(...after.center.map((v,i)=>v-before.center[i])); }).toBeLessThan(.1);
  await expect.poll(async () => Math.abs((await camera(page)).zoom-before.zoom)).toBeLessThan(.0001);
};
for (const [width,height] of [[1440,1000],[1024,768],[375,667]]) {
  test(`secondary WSI overview, selected ROI, tools and evidence preserve the camera at ${width}`, async ({page}) => {
    await page.setViewportSize({width,height}); await page.goto('/wsi.html'); await ready(page);
    await page.waitForFunction(()=>WSI.viewers.B.getFullyLoaded());
    await shot(page,`wsi-first-${width}`);
    await expect(page.locator('#inspector')).toBeHidden();
    await expect(page.locator('#showMask')).toBeHidden();
    await expect(page.locator('#scopeNote')).toBeVisible();
    await expect(page.locator('#scopeNote')).toContainText('핵 정답 없음');
    await expect(page.locator('#centerCoverage')).toContainText('미분석');
    if(width<=760) await page.locator('#toggleRegions').click();
    await page.locator('[data-roi="R1"]').click();
    await expect(page.locator('#modeCompare')).toHaveAttribute('aria-pressed','true');
    await expect(page.locator('#centerCoverage')).toContainText('R1 분석 범위');
    await page.waitForFunction(()=>WSI.viewers.B.getFullyLoaded());
    const before=await camera(page);
    await page.locator('#toggleResults').click();
    await page.locator('#processingDetails summary').first().click();
    await expect(page.locator('#roiMetrics')).toBeVisible();
    await page.locator('#closeResults').click(); await sameCamera(page,before);
    await page.locator('#displayTools summary').click(); await page.locator('#showMask').uncheck();
    await expect(page.locator('#overlayB [data-mask]')).toHaveCount(0);
    await page.locator('#showMask').check(); await page.locator('#displayTools summary').click();
    await sameCamera(page,before);
    await page.locator('#jumpDifference').click();
    await expect(page.locator('#viewerA')).toHaveAttribute('data-center',await page.locator('#viewerB').getAttribute('data-center'));
    if(await page.locator('#inspector').isHidden()) await page.locator('#toggleResults').click();
    await expect(page.locator('#differenceCounts')).toContainText('B 추가');
    await page.locator('#traceTools summary').click(); await page.locator('#traceFirst').click();
    await expect(page.locator('#candidateInfo')).toBeVisible();
    await expect(page.locator('#candidateInfo')).toContainText('억제');
    await page.locator('#closeResults').click();
    await expect(page.locator('#overlayB [data-selected]')).not.toHaveCount(0);
    await shot(page,`wsi-review-${width}`);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth && document.body.scrollHeight<=innerHeight)).toBe(true);
    expect((await page.locator('#viewerB').boundingBox()).height).toBeGreaterThan(200);
  });
  test(`secondary IHC selected cell precedes aggregate results and survives panel changes at ${width}`,async({page})=>{
    await page.setViewportSize({width,height}); await page.goto('/ihc.html'); await ready(page);
    await shot(page,`ihc-first-${width}`);
    await expect(page.locator('#testMacroF1')).toBeHidden();
    for(const id of ['sourceImage','cropImage','truthLabel','predictionLabel','selectedScore','caseExplanation'])await expect(page.locator('#'+id)).toBeVisible();
    const first=ihc.examples.find(e=>e.kind==='incorrect');
    await expect(page.locator('#selectedId')).toHaveText(first.id);
    await page.locator('#nextExample').click(); await ready(page);
    const id=await page.locator('#selectedId').textContent(); expect(id).not.toBe(first.id);
    await page.locator('#closeResults').click(); await expect(page.locator('#inspector')).toBeHidden();
    await page.locator('#toggleResults').click(); await expect(page.locator('#selectedId')).toHaveText(id);
    await page.locator('#prevExample').click(); await ready(page);await expect(page.locator('#selectedId')).toHaveText(first.id);
    await page.locator('#overallResults > summary').click();
    await expect(page.locator('#testMacroF1')).toHaveText(ihc.metrics.test.macro_f1.toFixed(3));
    await expect(page.locator('#testMacroF1')).toBeVisible();
    await page.locator('#overallResults > summary').click();
    await page.locator('#methodSources > summary').click();await expect(page.locator('#splitRows')).toBeVisible();
    await page.locator('#methodSources > summary').click();
    await page.locator('#filterCorrect').click(); await ready(page);
    await expect(page.locator('#verdict')).toHaveText('분류 일치');
    const example=ihc.examples.find(e=>e.id===page.url().split('example=')[1]);
    await expect(page.locator('#truthLabel')).toHaveText(ihc.classes[example.gt_class].label_ko);
    await expect(page.locator('#gtPoint')).toHaveAttribute('cx',String(example.center[0]+.5));
    await shot(page,`ihc-correct-${width}`);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth && document.body.scrollHeight<=innerHeight)).toBe(true);
    expect((await page.locator('#imageStage').boundingBox()).height).toBeGreaterThan(160);
  });
}
